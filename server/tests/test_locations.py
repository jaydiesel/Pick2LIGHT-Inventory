async def test_api_create_get_move_tree(client):
    t = (await client.post("/api/v1/location-types", json={"name": "Drawer"})).json()
    r = await client.post("/api/v1/locations", json={"name": "Garage"})
    assert r.status_code == 201
    garage = r.json()
    assert garage["code"].startswith("LOC-") and garage["light_children"] == "inherit"
    r = await client.post(
        "/api/v1/locations",
        json={"name": "A1", "parent_id": garage["id"], "location_type_id": t["id"]},
    )
    a1 = r.json()
    r = await client.get(f"/api/v1/locations/{a1['id']}")
    body = r.json()
    assert body["type_name"] == "Drawer"
    assert [p["name"] for p in body["path"]] == ["Garage", "A1"]
    assert body["path"][0].keys() == {"id", "name", "code"}

    shed = (await client.post("/api/v1/locations", json={"name": "Shed"})).json()
    r = await client.post(f"/api/v1/locations/{a1['id']}/move", json={"parent_id": shed["id"]})
    assert r.status_code == 200 and r.json()["parent_id"] == shed["id"]
    r = await client.post(f"/api/v1/locations/{shed['id']}/move", json={"parent_id": a1["id"]})
    assert r.status_code == 409

    nodes = (await client.get("/api/v1/locations/tree")).json()
    assert [n["name"] for n in nodes] == ["Garage", "Shed"]
    assert nodes[1]["children"][0]["name"] == "A1"
    assert nodes[1]["children"][0]["type_name"] == "Drawer"


async def test_api_patch_delete(client):
    a = (await client.post("/api/v1/locations", json={"name": "A"})).json()
    r = await client.patch(f"/api/v1/locations/{a['id']}", json={"name": "B", "grid_row": 2})
    assert r.json()["name"] == "B" and r.json()["grid_row"] == 2
    assert (await client.delete(f"/api/v1/locations/{a['id']}")).status_code == 204
    assert (await client.get(f"/api/v1/locations/{a['id']}")).status_code == 404
    assert (await client.get(f"/api/v1/barcodes/{a['code']}")).status_code == 404


async def test_delete_location_type_in_use_refused(client):
    t = (await client.post("/api/v1/location-types", json={"name": "Drawer"})).json()
    loc = (
        await client.post("/api/v1/locations", json={"name": "A", "location_type_id": t["id"]})
    ).json()
    assert (await client.delete(f"/api/v1/location-types/{t['id']}")).status_code == 409
    await client.delete(f"/api/v1/locations/{loc['id']}")
    assert (await client.delete(f"/api/v1/location-types/{t['id']}")).status_code == 204
