@pytest.fixture(autouse=True)
async def _restart_sequence(db):
    # Sequences are not rolled back with the test transaction; ALTER ... RESTART is.
    await db.execute(text("ALTER SEQUENCE location_code_seq RESTART WITH 1"))


async def test_location_code_autogenerated(db):
    a = await make_location(db, "A")
    b = await make_location(db, "B")
    assert (a.code, b.code) == ("LOC-0001", "LOC-0002")
    barcode = await lookup_barcode(db, "LOC-0001")
    assert barcode is not None
    assert (barcode.target_type, barcode.target_id, barcode.kind) == (
        "location",
        a.id,
        "location_code",
    )


async def test_manual_code_and_conflicts(db):
    a = await make_location(db, "A", code="MY-SHELF")
    assert a.code == "MY-SHELF"
    with pytest.raises(Conflict):
        await make_location(db, "B", code="MY-SHELF")


async def test_deleted_location_keeps_its_code_reserved(db):
    a = await make_location(db, "A")  # LOC-0001
    await delete_location(db, a.id)
    assert await lookup_barcode(db, "LOC-0001") is None
    with pytest.raises(Conflict):
        await make_location(db, "B", code="LOC-0001")
    await db.execute(text("ALTER SEQUENCE location_code_seq RESTART WITH 1"))
    c = await make_location(db, "C")
    assert c.code == "LOC-0001-2"


async def test_location_path(db):
    garage = await make_location(db, "Garage")
    cabinet = await make_location(db, "Cabinet", garage)
    a1 = await make_location(db, "A1", cabinet)
    path = await location_path(db, a1.id)
    assert [p.name for p in path] == ["Garage", "Cabinet", "A1"]
    assert path[-1].code == a1.code and path[0].id == garage.id


async def test_move_location_into_descendant_refused(db):
    garage = await make_location(db, "Garage")
    cabinet = await make_location(db, "Cabinet", garage)
    a1 = await make_location(db, "A1", cabinet)
    with pytest.raises(Conflict):
        await move_location(db, garage.id, a1.id)
    with pytest.raises(Conflict):
        await move_location(db, garage.id, garage.id)


async def test_move_location(db):
    garage = await make_location(db, "Garage")
    cabinet = await make_location(db, "Cabinet", garage)
    shed = await make_location(db, "Shed")
    moved = await move_location(db, cabinet.id, shed.id)
    assert moved.parent_id == shed.id
    assert [p.name for p in await location_path(db, cabinet.id)] == ["Shed", "Cabinet"]
    await move_location(db, cabinet.id, None)
    assert [p.name for p in await location_path(db, cabinet.id)] == ["Cabinet"]
    with pytest.raises(NotFound):
        await move_location(db, cabinet.id, 99999)


async def test_subtree_ids(db):
    garage = await make_location(db, "Garage")
    cabinet = await make_location(db, "Cabinet", garage)
    a1 = await make_location(db, "A1", cabinet)
    await make_location(db, "Shed")
    assert set(await subtree_ids(db, garage.id)) == {garage.id, cabinet.id, a1.id}
    assert await subtree_ids(db, a1.id) == [a1.id]


async def test_tree_nesting(db):
    shed = await make_location(db, "Shed")
    garage = await make_location(db, "Garage")
    await make_location(db, "B", garage)
    await make_location(db, "A", garage)
    gone = await make_location(db, "Gone", shed)
    await delete_location(db, gone.id)
    nodes = await tree(db)
    assert [n.name for n in nodes] == ["Garage", "Shed"]
    assert [c.name for c in nodes[0].children] == ["A", "B"]
    assert nodes[1].children == []


