import pytest
from factories import make_location

from pick2light.core.barcodes import lookup_barcode
from pick2light.core.locations import (
    LocationPatch,
    delete_location,
    location_path,
    move_location,
    subtree_ids,
    tree,
    update_location,
)
from pick2light.errors import Conflict


async def test_location_code_autogenerated(db):
    a = await make_location(db, "Garage")
    b = await make_location(db, "Office")
    assert a.code.startswith("LOC-") and len(a.code) == 8
    assert int(b.code[4:]) == int(a.code[4:]) + 1
    found = await lookup_barcode(db, a.code)
    assert found is not None and found.target_type == "location" and found.target_id == a.id


async def test_manual_code_taken_refused(db):
    a = await make_location(db, "Garage", code="GAR")
    assert a.code == "GAR"
    with pytest.raises(Conflict):
        await make_location(db, "Other", code="GAR")


async def test_location_path(db):
    garage = await make_location(db, "Garage")
    cab = await make_location(db, "Cabinet", parent=garage)
    a1 = await make_location(db, "A1", parent=cab)
    assert [p.name for p in await location_path(db, a1.id)] == ["Garage", "Cabinet", "A1"]


async def test_move_location_into_descendant_refused(db):
    garage = await make_location(db, "Garage")
    cab = await make_location(db, "Cabinet", parent=garage)
    with pytest.raises(Conflict):
        await move_location(db, garage.id, cab.id)
    with pytest.raises(Conflict):
        await move_location(db, garage.id, garage.id)


async def test_move_location(db):
    garage = await make_location(db, "Garage")
    office = await make_location(db, "Office")
    box = await make_location(db, "Box", parent=garage)
    await move_location(db, box.id, office.id)
    assert [p.name for p in await location_path(db, box.id)] == ["Office", "Box"]


async def test_subtree_ids(db):
    garage = await make_location(db, "Garage")
    cab = await make_location(db, "Cabinet", parent=garage)
    a1 = await make_location(db, "A1", parent=cab)
    await make_location(db, "Office")
    assert set(await subtree_ids(db, garage.id)) == {garage.id, cab.id, a1.id}


async def test_tree_nesting(db):
    garage = await make_location(db, "Garage")
    await make_location(db, "Zeta", parent=garage)
    await make_location(db, "Alpha", parent=garage)
    nodes = await tree(db)
    g = next(n for n in nodes if n.id == garage.id)
    assert [c.name for c in g.children] == ["Alpha", "Zeta"]


async def test_delete_location_with_children_refused(db):
    garage = await make_location(db, "Garage")
    await make_location(db, "Cabinet", parent=garage)
    with pytest.raises(Conflict):
        await delete_location(db, garage.id)


async def test_rename_code_reregisters_barcode(db):
    loc = await make_location(db, "Garage")
    old = loc.code
    await update_location(db, loc.id, LocationPatch(code="GARAGE"))
    assert await lookup_barcode(db, old) is None
    assert (await lookup_barcode(db, "GARAGE")).target_id == loc.id


async def test_location_type_in_use_cannot_be_deleted(db):
    from pick2light.core.categories import LocationTypeIn, create_location_type, delete_location_type

    lt = await create_location_type(db, LocationTypeIn(name="Drawer"))
    await make_location(db, "A1", location_type_id=lt.id)
    with pytest.raises(Conflict):
        await delete_location_type(db, lt.id)
