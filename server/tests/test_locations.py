async def test_update_location_changes_code_and_barcode(db):
    a = await make_location(db, "A")
    updated = await update_location(db, a.id, LocationPatch(name="A2", code="NEW-1", notes="n"))
    assert (updated.name, updated.code, updated.notes) == ("A2", "NEW-1", "n")
    assert await lookup_barcode(db, "LOC-0001") is None
    found = await lookup_barcode(db, "NEW-1")
    assert found is not None and found.target_id == a.id
    b = await make_location(db, "B")
    with pytest.raises(Conflict):
        await update_location(db, b.id, LocationPatch(code="NEW-1"))


